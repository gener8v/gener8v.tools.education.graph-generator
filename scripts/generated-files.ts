import { readFileSync, readdirSync } from "node:fs";
import { definitions } from "../src/core/definitions/index";
import { buildDescriptionTypes, buildSchema, buildToolSchema, buildVocabulary } from "../src/core/schema";
import { fixtureRegistry } from "../tests/fixtures/definitions/index";

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

/**
 * The package version as a module, for the header of exported source (CPSE-REQ-023). Read from
 * package.json, so the freshness check fails while it is stale; the release regenerates it after
 * the version bump (CPSE TICKET-009).
 */
// @spec CPSE-REQ-023
function versionModule(): string {
  const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")) as { version: unknown };
  if (typeof version !== "string") throw new Error("package.json has no version");
  return `// Generated by scripts/generate.ts from package.json. Do not edit.\n\nexport const PACKAGE_VERSION = ${JSON.stringify(version)};\n`;
}

/** `bar-graph` → `barGraph`, or `BarGraph` with `pascal`. */
function identifier(name: string, pascal: boolean): string {
  const camel = name.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());
  return pascal ? camel.charAt(0).toUpperCase() + camel.slice(1) : camel;
}

/**
 * The documentation site's stories: one per `examples/<name>.json`, in name order, each showing
 * the description, its graph and its type's input table (`docs/components/ExamplePage.tsx`). A
 * story file needs static exports, so it is generated, and a new example gets its story from
 * `pnpm generate` (graph-library CPSE TICKET-008). `examples/invalid/` is left out.
 */
// @spec CPSE-REQ-044
function exampleStories(): string {
  const names = readdirSync(new URL("../examples/", import.meta.url), { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => entry.name.slice(0, -".json".length))
    .sort();
  for (const name of names) {
    // The name becomes an identifier in the stories file.
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name)) throw new Error(`examples/${name}.json: name an example in lower-case words joined by hyphens`);
  }
  const lines = [
    "// Generated by scripts/generate.ts from examples/*.json. Do not edit.",
    "",
    'import type { Meta, StoryObj } from "@storybook/react-vite";',
    'import { ExamplePage } from "../components/ExamplePage";',
    ...names.map((name) => `import ${identifier(name, false)} from "../../examples/${name}.json";`),
    "",
    "// One story per example: the description, its graph and its type's input table (CPSE-REQ-044).",
    'const meta = { title: "Graph types", component: ExamplePage } satisfies Meta<typeof ExamplePage>;',
    "",
    "export default meta;",
    "",
    "type Story = StoryObj<typeof meta>;",
    ...names.flatMap((name) => [
      "",
      `export const ${identifier(name, true)}: Story = { name: ${JSON.stringify(name)}, args: { file: ${JSON.stringify(`${name}.json`)}, description: ${identifier(name, false)} } };`,
    ]),
  ];
  return `${lines.join("\n")}\n`;
}

/**
 * Every generated file, by repository path, with its content: the one list the generator writes
 * and the freshness test checks (quality review QR-009 on TICKET-005).
 */
export function generatedFiles(): Record<string, string> {
  return {
    "src/generated/description.ts": buildDescriptionTypes(definitions),
    "src/generated/schema.json": json(buildSchema(definitions)),
    "src/generated/tool-schema.json": json(buildToolSchema(definitions)),
    "src/generated/vocabulary.json": json(buildVocabulary(definitions)),
    "src/generated/version.ts": versionModule(),
    // Types from the test-only fixture definitions, for the type-level test (DEL-006).
    "tests/fixtures/generated/description.ts": buildDescriptionTypes(fixtureRegistry),
    // The documentation site's stories, one per example (graph-library CPSE TICKET-008).
    "docs/stories/examples.stories.tsx": exampleStories(),
  };
}
