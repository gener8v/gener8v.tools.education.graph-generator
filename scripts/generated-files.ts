import { readFileSync, readdirSync } from "node:fs";
import { definitions } from "../src/core/definitions/index";
import { buildDescriptionTypes, buildSchema, buildToolSchema, buildVocabulary } from "../src/core/schema";
import { fixtureRegistry } from "../tests/fixtures/definitions/index";

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

/**
 * The package version as a module, for the header of exported source (CPSE-REQ-023). Read from
 * package.json, so the freshness check fails while it is stale; the release regenerates it after
 * the version bump (CPSE TICKET-009).
 */
// @spec CPSE-REQ-023
function versionModule(): string {
  const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")) as { version: unknown };
  if (typeof version !== "string") throw new Error("package.json has no version");
  return `// Generated by scripts/generate.ts from package.json. Do not edit.\n\nexport const PACKAGE_VERSION = ${JSON.stringify(version)};\n`;
}

/** `bar-graph` → `BarGraph`; a leading digit stays, so the result is not yet an identifier. */
function pascal(name: string): string {
  const camel = name.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

/** What the stories file already declares or imports, so no story is exported under one of these. */
const TAKEN_EXPORTS: ReadonlySet<string> = new Set(["Meta", "Story", "StoryObj", "ExamplePage"]);

/**
 * The identifiers the stories file uses for one example (quality review QR-005 on TICKET-008): the
 * imported description is `example` + the name in Pascal case, so a name that is a reserved word
 * (`class`, `default`) cannot become a bad import; the story is the name in Pascal case, prefixed
 * with `Example` when it starts with a digit or is a name the file uses itself. A name is lower-case
 * words joined by hyphens, so the result is a valid identifier.
 */
export function storyIdentifiers(name: string): { description: string; story: string } {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) throw new Error(`examples/${name}.json: name an example in lower-case words joined by hyphens`);
  const base = pascal(name);
  return { description: `example${base}`, story: /^[0-9]/.test(base) || TAKEN_EXPORTS.has(base) ? `Example${base}` : base };
}

/**
 * The stories file for these example names, in this order: one story per example, showing the
 * description, its graph and its type's input table (`docs/components/ExamplePage.tsx`). The file
 * name is bound in the story's `render`, not an arg, so a link or a message cannot change it
 * (security review SEC-002 on TICKET-008).
 */
// @spec CPSE-REQ-044
export function storiesFile(names: readonly string[]): string {
  const identifiers = names.map((name) => ({ name, ...storyIdentifiers(name) }));
  const seen = new Map<string, string>();
  for (const { name, story } of identifiers) {
    const other = seen.get(story);
    if (other !== undefined) throw new Error(`examples/${name}.json and examples/${other}.json both become the story ${story}; rename one`);
    seen.set(story, name);
  }
  const lines = [
    "// Generated by scripts/generate.ts from examples/*.json. Do not edit.",
    "",
    'import type { Meta, StoryObj } from "@storybook/react-vite";',
    'import { ExamplePage } from "../components/ExamplePage";',
    ...identifiers.map(({ name, description }) => `import ${description} from "../../examples/${name}.json";`),
    "",
    "// One story per example: the description, its graph and its type's input table (CPSE-REQ-044).",
    "// Only the description is an arg; the file name is bound in `render`, so it is not one.",
    'const meta = { title: "Graph types", component: ExamplePage } satisfies Meta<typeof ExamplePage>;',
    "",
    "export default meta;",
    "",
    "type Story = StoryObj<{ description: unknown }>;",
    ...identifiers.flatMap(({ name, description, story }) => [
      "",
      `export const ${story}: Story = {`,
      `  name: ${JSON.stringify(name)},`,
      `  args: { description: ${description} },`,
      `  render: (args) => <ExamplePage {...args} file=${JSON.stringify(`${name}.json`)} />,`,
      "};",
    ]),
  ];
  return `${lines.join("\n")}\n`;
}

/**
 * The documentation site's stories: one per `examples/<name>.json`, in name order. A story file
 * needs static exports, so it is generated, and a new example gets its story from `pnpm generate`
 * (graph-library CPSE TICKET-008). `examples/invalid/` is left out.
 */
// @spec CPSE-REQ-044
function exampleStories(): string {
  const names = readdirSync(new URL("../examples/", import.meta.url), { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => entry.name.slice(0, -".json".length))
    .sort();
  return storiesFile(names);
}

/**
 * Every generated file, by repository path, with its content: the one list the generator writes
 * and the freshness test checks (quality review QR-009 on TICKET-005).
 */
export function generatedFiles(): Record<string, string> {
  return {
    "src/generated/description.ts": buildDescriptionTypes(definitions),
    "src/generated/schema.json": json(buildSchema(definitions)),
    "src/generated/tool-schema.json": json(buildToolSchema(definitions)),
    "src/generated/vocabulary.json": json(buildVocabulary(definitions)),
    "src/generated/version.ts": versionModule(),
    // Types from the test-only fixture definitions, for the type-level test (DEL-006).
    "tests/fixtures/generated/description.ts": buildDescriptionTypes(fixtureRegistry),
    // The documentation site's stories, one per example (graph-library CPSE TICKET-008).
    "docs/stories/examples.stories.tsx": exampleStories(),
  };
}
